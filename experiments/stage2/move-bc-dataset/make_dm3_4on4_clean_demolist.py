#!/usr/bin/env python3
"""Produce the CLEAN 'ONLY dm3 4on4' demo allowlist for MOVE-BC training.

The original pool (selfpov_4on4_demolist.tsv, 472 demos) was assembled with a
filename heuristic and leaked non-4on4 content (trick/comedy/CTF/domination/3v3
demos) AND demos whose filename says "dm3" but whose actual level is something
else. This filter removes both, using:

  1. CONTENT-TRUE map: the manifest's parsed level title must be dm3
     ("The Abandoned Base") -- catches "dm3"-in-filename demos really on e1m2/
     e3m6/etc.
  2. MODE-TAG exclusion: drop demos whose CHTV filename tags an explicitly
     non-4on4 mode (Trick / CTF / HowTo / Comedy / Domination / 3v3). These tags
     are reliable negative signals.
  3. build_ok: the demo parsed.

NOT yet enforced here (needs demo-content parsing; load-bearing only for the
per-player tier, see TRAINED_DEMOS / status doc): roster-verified 4on4 (==8
connected players) for the untagged SmackDown* tournament bulk, and correct
POV-player attribution from in-demo userinfo. Those are a documented follow-up.

Writes:
  dm3_4on4_clean_allowlist.txt   (one demo filename per line; build_dataset input)
  dm3_4on4_clean_selection.md    (kept/excluded counts + full excluded list w/ reasons)
"""
from __future__ import annotations

import json
import re
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
MANIFEST = HERE / "manifest.json"
ALLOWLIST = HERE / "dm3_4on4_clean_allowlist.txt"
REPORT = HERE / "dm3_4on4_clean_selection.md"

DM3_TITLE = "The Abandoned Base"
NON_4ON4 = re.compile(r"_(QuakeWorld|QW|QWCA)_(Trick|CTF|HowTo|Comedy|Domination|3v3)__", re.I)


def main():
    pool = json.loads(MANIFEST.read_text())["demos"]
    kept, excluded = [], []
    reasons = Counter()
    for d in pool:
        name = d["demo"]
        if not d.get("ok"):
            excluded.append((name, "build_fail")); reasons["build_fail"] += 1; continue
        if d.get("map") != DM3_TITLE:
            excluded.append((name, f"non_dm3_map({d.get('map')!r})")); reasons["non_dm3_map"] += 1; continue
        m = NON_4ON4.search(name)
        if m:
            tag = m.group(2).lower()
            excluded.append((name, f"mode:{tag}")); reasons[f"mode:{tag}"] += 1; continue
        kept.append(name)

    ALLOWLIST.write_text("\n".join(sorted(kept)) + "\n", encoding="utf-8")

    md = []
    md.append("# Clean 'ONLY dm3 4on4' demo selection\n")
    md.append("Generated by `make_dm3_4on4_clean_demolist.py` from `manifest.json` "
              "(content-true map) + CHTV mode-tag exclusion. Allowlist: "
              "[`dm3_4on4_clean_allowlist.txt`](dm3_4on4_clean_allowlist.txt).\n")
    md.append(f"- pool: **{len(pool)}**")
    md.append(f"- **kept (clean dm3 4on4): {len(kept)}**")
    md.append(f"- excluded: {len(excluded)}\n")
    md.append("## Exclusion reasons\n")
    md.append("| reason | count |")
    md.append("|---|---|")
    for r, c in sorted(reasons.items(), key=lambda x: -x[1]):
        md.append(f"| {r} | {c} |")
    md.append("\n## Not yet enforced (follow-up, per-player tier)\n")
    md.append("- **Roster-verified 4on4** for the untagged SmackDown* tournament bulk "
              "(needs in-demo connected-player count via `engine/demoparser`). Retained "
              "here as curated 4on4, not content-verified.")
    md.append("- **POV-player re-attribution** from in-demo userinfo (the current "
              "`player` column is a filename heuristic and unreliable for some demos).\n")
    md.append("## Full excluded list\n")
    md.append("| reason | demo |")
    md.append("|---|---|")
    for n, r in sorted(excluded, key=lambda x: (x[1], x[0])):
        md.append(f"| {r} | {n} |")
    md.append("")
    REPORT.write_text("\n".join(md), encoding="utf-8")

    print(f"pool={len(pool)} kept={len(kept)} excluded={len(excluded)}")
    print("reasons:", dict(reasons))
    print(f"wrote {ALLOWLIST}")
    print(f"wrote {REPORT}")


if __name__ == "__main__":
    main()
