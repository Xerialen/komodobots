REPO = Path(__file__).resolve().parent.parent
SNG_EVID = REPO / "experiments" / "dm3_sng_to_rl_observability" / "evidence"
PMOVE_EVID = REPO / "experiments" / "nav_doctrine" / "evidence" / "pmove"


def resolve_cmds(path):
    """Live artifacts/ copy first, committed evidence fallback, so the
    documented no-arg reproduction works from a clean checkout (Codex PR #60)."""
    p = Path(path)
    if p.exists():
        return p
    fallback = SNG_EVID / p.name
    if fallback.exists():
        return fallback
    raise SystemExit(f"{p} missing and no committed copy at {fallback}")


DEFAULT_BOTLOG = "artifacts/lab-runs/20260609T214845Z/moveprobe-commands.json"
COMMITTED_BOTLOG_GZ = PMOVE_EVID / "moveprobe-commands.20260609T214845Z.json.gz"


def resolve_botlog(path):
    """Fallback rule for the DEFAULT botlog only: every run dir has a
    moveprobe-commands.json, so a name-keyed fallback would silently swap a
    missing log from some OTHER run for the committed 2148 one. An explicit
    --botlog that does not exist is therefore a hard error. The committed copy
    is gzipped (8.3 MB -> 261 KB); decompress to a temp file for the loader."""
    p = Path(path)
    if p.exists():
        return p
    if str(path).replace("\\", "/") != DEFAULT_BOTLOG:
        raise SystemExit(f"--botlog {p} missing (no fallback for non-default logs)")
    if not COMMITTED_BOTLOG_GZ.exists():
        raise SystemExit(f"{p} missing and no committed copy at {COMMITTED_BOTLOG_GZ}")
    tmp = Path(tempfile.gettempdir()) / COMMITTED_BOTLOG_GZ.stem  # strips .gz
    with gzip.open(COMMITTED_BOTLOG_GZ, "rb") as src, open(tmp, "wb") as dst:
        shutil.copyfileobj(src, dst)
    return tmp


def main():
    global args
    ap = argparse.ArgumentParser()
    ap.add_argument("--bsp", default=r"C:\nQuake\qw\maps\dm3.bsp")
    ap.add_argument("--cmds", default="artifacts/replay/dm3_sng_to_rl.cmds")
    ap.add_argument("--botlog",
                    default="artifacts/lab-runs/20260609T214845Z/moveprobe-commands.json")
    ap.add_argument("--out", default="artifacts/pmove-validation")
    args = ap.parse_args()

    if not Path(args.bsp).exists():
        raise SystemExit(
            f"{args.bsp} missing. dm3.bsp is original id content and cannot be "
            "committed; point --bsp at any Quake install's copy "
            r"(e.g. C:\nQuake\qw\maps\dm3.bsp or ~/nquake/qw/maps/dm3.bsp).")
    args.cmds = str(resolve_cmds(args.cmds))
    args.botlog = str(resolve_botlog(args.botlog))

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    world = WorldModel.load(args.bsp)

    print("== human replay ==")
    hv = human_validation(world, args.cmds)
    print(json.dumps({k: v for k, v in hv.items() if k != "rows"}, indent=2))

    print("== bot replay ==")
    bv = bot_validation(world, args.botlog)
    print(json.dumps({k: v for k, v in bv.items() if k != "rows"}, indent=2))

    (out / "human-replay.json").write_text(json.dumps(
        {k: v for k, v in hv.items()}, indent=1))
    (out / "bot-replay.json").write_text(json.dumps(
        {k: v for k, v in bv.items()}, indent=1))

    hs, bs = hv["summary"], bv
    report = REPORT_TEMPLATE.format(
        cmds_name=Path(args.cmds).name,
        human_frames=hs["frames_simulated"] + 1,
        tele_frames=", ".join(str(t) for t in hv["teleport_frames"]),
        human_first_div=hs["first_divergence_frame"] or "none",
        human_max=hs["max_err"], human_mean=hs["mean_err"], human_p95=hs["p95_err"],
        human_water=hs["water_frames"],
        edge_frame=hv["edge_frame"], edge_err=hv["edge_err_qu"],
        sim_edge_vh=hv["sim_edge_vh"], rec_edge_vh=hv["rec_edge_vh"],
        rec_edge_vh_hi=round(hv["rec_edge_vh"] + 1.5, 1),
        human_verdict="PASS" if hv["pass"] else "FAIL",
        bot_frames=BOT_FRAMES,
        dup_count=bs["duplicate_records_collapsed"],
        bot_anch_max=bs["anchored"]["max_err"],
        bot_anch_mean=bs["anchored"]["mean_err"],
        bot_anch_p95=bs["anchored"]["p95_err"],
        bot_free_div=bs["free_run"]["first_divergence_frame"] or "none",
        segment=SEGMENT,
        seg_ok=bs["segmented"]["segments_under_4qu"],
        seg_total=bs["segmented"]["segments_total"],
        seg_list=bs["segmented"]["per_segment_max_err"],
        bot_verdict="PASS (per-step) / input-limited (free-run)"
                    if bs["pass_anchored"] else "FAIL",
        movevars=json.dumps(MoveVars().as_dict(), indent=2),
    )
    (out / "report.md").write_text(report, encoding="utf-8")
    print(f"\nwrote {out / 'report.md'}")
    print(f"wrote {out / 'human-replay.json'}")
    print(f"wrote {out / 'bot-replay.json'}")


if __name__ == "__main__":
    main()
