# The lab server ate the bot's first post-spawn jump cmd (record index 2 in the
# 20260609T214845Z log) even though buttons=2 / onground / no prior press —
# behaviour equals jump_held==true. Single-frame server-side input seam; see
# report. Forced here so the free-run covers the full window.
BOT_FORCE_JUMP_HELD = (2,)
BOT_FRAMES = 2000
SEGMENT = 77  # ~1 s at 77 fps


def human_validation(world, cmds_path):
    frames = load_cmds_file(cmds_path)
    tele = detect_teleports(frames)
    summary, rows = replay(world, frames, reanchor_at=tele)

    bsp = bsp_geom.Bsp.load(args.bsp)
    geom = bsp_geom.derive_jump_geom(bsp, cmds_path)
    edge_frame = geom["launch_edge"]["frame"]
    rec_vh = math.hypot(frames[edge_frame]["velocity"][0],
                        frames[edge_frame]["velocity"][1])
    sim_vh = speed_at_frame(rows, edge_frame)
    edge_row = next(r for r in rows if r["frame"] == edge_frame)

    tracked_to_edge = all(r["err"] <= 4.0 for r in rows
                          if r["frame"] <= edge_frame and not r["teleport_reanchor"])
    edge_ok = sim_vh is not None and abs(sim_vh - rec_vh) <= 2.0
    return {
        "summary": summary,
        "teleport_frames": tele,
        "edge_frame": edge_frame,
        "edge_err_qu": edge_row["err"],
        "sim_edge_vh": sim_vh,
        "rec_edge_vh": round(rec_vh, 1),
        "tracked_to_edge": tracked_to_edge,
        "pass": tracked_to_edge and edge_ok and summary["water_frames"] == 0,
        "rows": rows,
    }


def bot_validation(world, botlog_path):
    raw_n = len(json.loads(Path(botlog_path).read_text())["commands"])
    frames = load_botlog(botlog_path)  # duplicate-collapsed
    dups = raw_n - len(frames)

    anchored, _ = replay(world, frames, max_frames=BOT_FRAMES, anchored=True,
                         force_jump_held=BOT_FORCE_JUMP_HELD)
    free, free_rows = replay(world, frames, max_frames=BOT_FRAMES,
                             force_jump_held=BOT_FORCE_JUMP_HELD)
    seg, seg_rows = replay(world, frames, max_frames=BOT_FRAMES,
                           reanchor_every=SEGMENT,
                           force_jump_held=BOT_FORCE_JUMP_HELD)
    # per-segment max error
    seg_max = {}
    for r in seg_rows:
        s_idx = (r["frame"] - 1) // SEGMENT
        if r["err"] > seg_max.get(s_idx, 0.0):
            seg_max[s_idx] = r["err"]
    segments = [round(seg_max[i], 2) for i in sorted(seg_max)]
    return {
        "duplicate_records_collapsed": dups,
        "anchored": anchored,
        "free_run": free,
        "segmented": {
            "segment_frames": SEGMENT,
            "per_segment_max_err": segments,
            "segments_under_4qu": sum(1 for e in segments if e < 4.0),
            "segments_total": len(segments),
        },
        "pass_anchored": anchored["p95_err"] is not None and anchored["p95_err"] < 0.05,
        "rows": free_rows,
    }


